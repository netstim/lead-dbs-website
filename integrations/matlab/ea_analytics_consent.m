function ea_analytics_consent()
% Explicit, revocable preference. Called from a user-selected settings action.
message = ['Share optional Lead-DBS usage statistics? ', ...
    'This sends the tool name, Lead-DBS version and MATLAB version. ', ...
    'The collector uses your network address to estimate country and ', ...
    'deduplicate requests with a daily pseudonym scheduled for deletion after 31 days. ', ...
    'Server access logs follow the service privacy notice. ', ...
    'No patient data, paths or project names are sent. ', ...
    'You can turn reporting off here at any time.'];
choice = questdlg(message, 'Optional usage statistics', 'Enable', 'Disable', 'Cancel', 'Cancel');
if strcmp(choice, 'Enable')
    setpref('LeadDBS', 'analyticsEnabled', true);
elseif strcmp(choice, 'Disable')
    setpref('LeadDBS', 'analyticsEnabled', false);
end
end
